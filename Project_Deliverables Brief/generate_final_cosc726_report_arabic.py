def convert_arabic_docx_to_pdf(docx_path):
    """Converts the Arabic .docx file to a pristine .pdf using Word COM automation."""
    pdf_path = docx_path.replace(".docx", ".pdf")
    print(f"[INFO] Converting Arabic report '{docx_path}' to PDF via Word COM...")
    try:
        import win32com.client
        word = win32com.client.Dispatch("Word.Application")
        word.Visible = False
        wdoc = word.Documents.Open(os.path.abspath(docx_path))
        wdoc.SaveAs(os.path.abspath(pdf_path), FileFormat=17)
        wdoc.Close()
        word.Quit()
        print(f"[SUCCESS] Arabic Report PDF successfully created: {pdf_path}")

        # Replicate to Documentation and Root
        replications = [
            os.path.join(DOCS_DIR, "COSC726_Project_Team_Health_Report_Arabic.pdf"),
            os.path.join(PROJECT_ROOT, "COSC726_Project_Team_Health_Report_Arabic.pdf"),
            os.path.join(OUTPUT_DIR, "COSC726_Project_Mohamed_Abuelgasim_Report_Arabic.pdf")
        ]
        for dest in replications:
            try:
                shutil.copy2(pdf_path, dest)
                print(f"[SUCCESS] Replicated Arabic PDF: {dest}")
            except Exception as e:
                print(f"[WARNING] Replication failed for {dest}: {e}")

        return pdf_path
    except Exception as e:
        print(f"[ERROR] Arabic Report PDF conversion failed: {e}")
        return None

