def convert_qa_docx_to_pdf(docx_path):
    """Converts the Q&A Word file to PDF using Word COM."""
    pdf_path = docx_path.replace(".docx", ".pdf")
    print(f"[INFO] Converting '{docx_path}' to PDF via Word COM...")
    try:
        import win32com.client
        word = win32com.client.Dispatch("Word.Application")
        word.Visible = False
        wdoc = word.Documents.Open(os.path.abspath(docx_path))
        wdoc.SaveAs(os.path.abspath(pdf_path), FileFormat=17)
        wdoc.Close()
        word.Quit()
        print(f"[SUCCESS] Defense Q&A PDF created: {pdf_path}")

        # Copy to Documentation
        docs_pdf_path = os.path.join(DOCS_DIR, "COSC726_Defense_QA_Guide_Arabic.pdf")
        try:
            shutil.copy2(pdf_path, docs_pdf_path)
            print(f"[SUCCESS] Replicated Defense Q&A PDF to Documentation: {docs_pdf_path}")
        except Exception as e:
            print(f"[WARNING] Replication failed: {e}")

        # Copy to Root
        root_pdf_path = os.path.join(PROJECT_ROOT, "COSC726_Defense_QA_Guide_Arabic.pdf")
        try:
            shutil.copy2(pdf_path, root_pdf_path)
            print(f"[SUCCESS] Replicated Defense Q&A PDF to Root: {root_pdf_path}")
        except Exception as e:
            print(f"[WARNING] Replication to root failed: {e}")

        return pdf_path
    except Exception as e:
        print(f"[ERROR] Q&A PDF conversion failed: {e}")
        return None

